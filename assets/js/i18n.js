const LANG_KEY = "singgahperak_lang";
const LANG_LABELS = { en: "English", ms: "Bahasa Melayu", th: "ไทย", id: "Bahasa Indonesia", zh: "中文" };

function getLang() {
  let l = null;
  try {
    l = localStorage.getItem(LANG_KEY);
  } catch {
    /* ignore */
  }
  return LANGS.includes(l) ? l : "ms";
}

function setLang(l) {
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {
    /* ignore */
  }
}

function t(key, vars) {
  const lang = getLang();
  let s = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

// Pick a field from a {en, ms, ...} object in the current language.
function tr(obj) {
  if (!obj) return "";
  return obj[getLang()] || obj.en;
}

// Fill every [data-i18n] element and build the language picker.
function applyI18n() {
  document.documentElement.lang = getLang();
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  const sel = document.getElementById("lang");
  if (sel && !sel.options.length) {
    for (const l of LANGS) {
      const o = document.createElement("option");
      o.value = l;
      o.textContent = LANG_LABELS[l];
      sel.appendChild(o);
    }
  }
  if (sel) sel.value = getLang();
}
